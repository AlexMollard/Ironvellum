#!/usr/bin/env python3
"""Builds the exercise-art assets and the Kotlin tables the app reads from library.json, mapping.json and guides.json.

    python3 -P tools/exercise_art/build.py --src <upstream dir>          # rewrites assets and the generated Kotlin
    python3 -P tools/exercise_art/build.py --check                       # exits 1 if the Kotlin is stale (no --src needed)
    python3 -P tools/exercise_art/build.py --owner-only                  # trace the art submodule's approved PNGs (see ART_STORAGE.md)
    python3 -P tools/exercise_art/build.py --reweight                    # redraws the shipped assets at art.WEIGHT (no --src)

<upstream dir> holds clones of bryllim/workout-guide and everkinetic/data as wg/ and ek/ (see upstream.py, art.py).
Outputs:
    app/src/main/assets/exercise_art/<art id>.paths  an exercise's drawings as vector paths, registered to one window (art.py)
    art_report.json                                  which source frames were kept, and why the others were dropped
    domain/ExerciseLibrary.kt                        the movements the library adds: catalogue row, tier, load, gear, muscles
    domain/ExerciseArtIndex.kt                       movement and technique -> art id, frame count
    domain/LibraryGuides.kt                          a how-to for each added movement
Nothing is generated at build time of the app: the Kotlin and the assets are committed, and --check keeps them honest.
"""
import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
KT = ROOT / "app" / "src" / "main" / "kotlin" / "com" / "ironvellum" / "app" / "domain"
ART = ROOT / "art"                          # git submodule: github.com/AlexMollard/Open-Exercise-Art
ART_PNG = ART / "png"                       # png/<slug>.png, the only masters
CATALOGUE = ART / "catalogue.json"          # open-exercise-art-v1: exercises[].id, png.file, png.sha256
MISSING = HERE / "missing.json"
REPLACEMENTS = HERE / "replacement-catalog.json"
FRAME_COUNTS = HERE / "frame-counts.json"   # a reviewed still asks for 1 frame instead of the entry's count
DOCS = ROOT / "docs" / "art"
REPORT = HERE / "art_report.json"
ASSETS = ROOT / "app" / "src" / "main" / "assets" / "exercise_art"
CHUNK = 30
HEADER = "// Generated by tools/exercise_art/build.py from library.json, mapping.json and guides.json. Do not edit by hand.\n"
UNILATERAL = re.compile(r"(?i)one-arm|single-|one-leg|lunge|split squat|step-up|step-down|pistol|shrimp|skater|bird dog|side-lying|"
                        r"clamshell|fire hydrant|donkey kick|kickback|alternating|stork|curtsy|cossack|side squat|\bsingle\b")


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def num(x):
    return ("%g" % x) if x != int(x) else "%d.0" % x


def load():
    lib = json.loads((HERE / "library.json").read_text(encoding="utf-8"))
    mp = json.loads((HERE / "mapping.json").read_text(encoding="utf-8"))
    guides = json.loads((HERE / "guides.json").read_text(encoding="utf-8"))
    return lib, mp, guides


def final_frames(report):
    """art id -> number of frames the shipped file holds (source frames the pipeline dropped are not counted)."""
    return {k: len(v["kept"]) for k, v in report.items()}


def art_table(lib, mp, report=None):
    """lower-case movement name -> (art id, frames): mapped existing movements, added ones, and techniques' own names.
    With a report, frames is what the shipped file holds."""
    fin = final_frames(report) if report else {}
    table = {}
    for m in mp["mapped"]:
        if m["used"]:
            table[m["exercise"]] = (m["art"], m["frames"])
    for e in lib:
        table[e["name"]] = (e["art"], e["frames"])
    for sk, t in mp["techniques"].items():
        if not t.get("proxy"):  # a proxy drawing shows another movement: it is the technique's, never the catalogue row's
            table.setdefault(sk, (t["art"], t["frames"]))
    # Approved owner drawings also replace art for movements added by the library.
    for m in mp["mapped"]:
        if m["used"] and m.get("confidence") == "owner":
            table[m["exercise"]] = (m["art"], m["frames"])
    return {k: (a, fin.get(a, f)) for k, (a, f) in table.items()}


def wrap(lines):
    return "\r\n".join(lines) + "\r\n"


def library_kt(lib):
    rows = []
    for e in lib:
        p = e["profile"]
        uni = bool(UNILATERAL.search(e["name"])) and e["metric"] in ("REPS",) and not e["category"]
        muscles = ", ".join("Muscle.%s to %s" % (k, num(v)) for k, v in p["muscles"].items())
        gear = "emptyList()" if not e["gear"] else "listOf(%s)" % ", ".join(
            "setOf(%s)" % ", ".join("Gear." + g for g in alt) for alt in e["gear"])
        rows.append(
            "row(%s, %s, %s, %s, %s, %d, %s, %s, MovementPattern.%s, %s, %s, %s, %s, %s)" % (
                q(e["name"]), "MuscleGroup." + e["group"], "ExerciseMetric." + e["metric"],
                "true" if e["weighted"] else "false", q(e["category"]), e["tier"], num(e["loadFactor"]), gear,
                p["pattern"], "true" if p["compound"] else "false", "true" if p["stretchBias"] else "false",
                "true" if p["noLead"] else "false", "true" if uni else "false", "linkedMapOf(%s)" % muscles))
    chunks = [rows[i:i + CHUNK] for i in range(0, len(rows), CHUNK)]
    out = [HEADER.rstrip("\n"), "package com.ironvellum.app.domain", "",
           "/**",
           " * The movements the exercise library adds to the catalogue, each with everything the other tables need: its row,",
           " * difficulty tier, load transmission, gear and muscle shares. Seed, MovementDifficulty, GearRequirements and",
           " * MuscleMap read their library rows from here, so a movement cannot be added to one and forgotten in another.",
           " * The shares borrow the profile of the closest existing movement (see tools/exercise_art/draft_library.py).",
           " * Library movements are never prescribed by the program generator ([ProgramGenerator.eligible]); they are for",
           " * logging, browsing and the picker.",
           " */",
           "internal object ExerciseLibrary {",
           "",
           "    class Row(",
           "        val name: String,",
           "        val group: MuscleGroup,",
           "        val metric: ExerciseMetric,",
           "        val weighted: Boolean,",
           "        val category: String,",
           "        val tier: Int,",
           "        val loadFactor: Double,",
           "        val gear: List<Set<Gear>>,",
           "        val profile: ExerciseProfile,",
           "    )",
           "",
           "    val rows: List<Row> by lazy {",
           "        buildList {"]
    for i in range(len(chunks)):
        out.append("            part%d()" % (i + 1))
    out += ["        }", "    }", "",
            "    /** Lower-case names of every library movement. */",
            "    val names: Set<String> by lazy { rows.map { it.name.lowercase() }.toSet() }", "",
            "    fun isLibraryOnly(name: String): Boolean = name.trim().lowercase() in names", "",
            "    private fun MutableList<Row>.row(",
            "        name: String, group: MuscleGroup, metric: ExerciseMetric, weighted: Boolean, category: String, tier: Int,",
            "        loadFactor: Double, gear: List<Set<Gear>>, pattern: MovementPattern, compound: Boolean, stretchBias: Boolean,",
            "        noLead: Boolean, unilateral: Boolean, muscles: Map<Muscle, Double>,",
            "    ) {",
            "        add(",
            "            Row(",
            "                name, group, metric, weighted, category, tier, loadFactor, gear,",
            "                ExerciseProfile(muscles, pattern, compound, stretchBias, noLeadByDesign = noLead, unilateral = unilateral),",
            "            ),",
            "        )",
            "    }", ""]
    for i, ch in enumerate(chunks):
        out.append("    private fun MutableList<Row>.part%d() {" % (i + 1))
        for r in ch:
            out.append("        " + r)
        out.append("    }")
        out.append("")
    out.append("}")
    return wrap(out)


def index_kt(lib, mp, report):
    table = art_table(lib, mp, report)
    out = [HEADER.rstrip("\n"), "package com.ironvellum.app.domain", "",
           "/** One exercise drawing: the asset `exercise_art/<id>.paths`, holding [frames] poses as vector paths. */",
           "data class ArtRef(val id: String, val frames: Int)", "",
           "/**",
           " * Which drawing shows which movement. [forName] is every catalogue movement with a drawing. [forTechnique] is the",
           " * skill-tree techniques that have one: their own drawing, or a proxy, the drawing of the movement they build on,",
           " * which [shows] names so the sheet can say what the picture is. Names are matched like the other tables: trimmed",
           " * and lower-cased.",
           " */",
           "object ExerciseArtIndex {", "",
           "    private fun key(name: String) = name.trim().lowercase()", "",
           "    fun forName(name: String): ArtRef? = byName[key(name)]", "",
           "    fun forTechnique(skillName: String): ArtRef? = byTechnique[key(skillName)]", "",
           "    /** The movement a proxy drawing shows, or null when the technique's drawing is its own movement. */",
           "    fun shows(skillName: String): String? = proxies[key(skillName)]", "",
           "    /** Every art id the index uses, for the coverage test. */",
           "    val ids: Set<String> get() = (byName.values + byTechnique.values).map { it.id }.toSet()", "",
           "    val names: Set<String> get() = byName.keys", "",
           "    val techniques: Set<String> get() = byTechnique.keys", "",
           "    private fun ref(id: String, frames: Int) = ArtRef(id, frames)", "",
           "    private val byName: Map<String, ArtRef> = mapOf("]
    for name in sorted(table, key=str.lower):
        aid, fr = table[name]
        out.append("        %s to ref(%s, %d)," % (q(name.lower()), q(aid), fr))
    out += ["    )", "", "    private val byTechnique: Map<String, ArtRef> = mapOf("]
    for sk in sorted(mp["techniques"], key=str.lower):
        t = mp["techniques"][sk]
        out.append("        %s to ref(%s, %d)," % (q(sk.lower()), q(t["art"]), final_frames(report).get(t["art"], t["frames"])))
    out += ["    )", "", "    private val proxies: Map<String, String> = mapOf("]
    for sk in sorted(mp["techniques"], key=str.lower):
        t = mp["techniques"][sk]
        if t.get("proxy"):
            out.append("        %s to %s," % (q(sk.lower()), q(t["exercise"])))
    out += ["    )", "}"]
    return wrap(out)


def guides_kt(lib, guides):
    names = [e["name"] for e in lib]
    chunks = [names[i:i + CHUNK] for i in range(0, len(names), CHUNK)]
    out = [HEADER.rstrip("\n"), "package com.ironvellum.app.domain", "",
           "/**",
           " * How-to guides for the library's movements, keyed like [ExerciseGuides]. Steps from Everkinetic records are",
           " * adapted from its CC BY-SA 4.0 text (credited under Support); the rest were written for this app.",
           " */",
           "internal object LibraryGuides {", "",
           "    val guides: Map<String, ExerciseGuide> by lazy {",
           "        buildMap {"]
    for i in range(len(chunks)):
        out.append("            part%d()" % (i + 1))
    out += ["        }", "    }", ""]
    for i, ch in enumerate(chunks):
        out.append("    private fun MutableMap<String, ExerciseGuide>.part%d() {" % (i + 1))
        for n in ch:
            g = guides[n]
            out.append("        put(")
            out.append("            %s," % q(n.lower()))
            out.append("            ExerciseGuide(")
            out.append("                setup = %s," % q(g["setup"]))
            out.append("                steps = listOf(")
            for s in g["steps"]:
                out.append("                    %s," % q(s))
            out.append("                ),")
            out.append("                cues = listOf(%s)," % ", ".join(q(c) for c in g["cues"]))
            out.append("                commonMistakes = listOf(%s)," % ", ".join(q(c) for c in g["mistakes"]))
            out.append("            ),")
            out.append("        )")
        out.append("    }")
        out.append("")
    out.append("}")
    return wrap(out)


def technique_doc(mp, report):
    """docs/art/skill-technique-art.json: for each skill-tree technique, which drawing it shows and whether it is its own."""
    skills = re.findall(r'SkillDef\(\s*"([^"]+)"', (KT / "Skills.kt").read_text(encoding="utf-8"))
    fin = final_frames(report)
    rows = []
    for name in skills:
        t = mp["techniques"].get(name)
        if t is None:
            rows.append({"name": name, "status": "glyph"})
        else:
            rows.append({"name": name, "status": "proxy" if t.get("proxy") else "exact", "drawing": t["art"],
                         "frames": fin.get(t["art"], t["frames"]), "shows": t["exercise"]})
    count = {s: sum(1 for r in rows if r["status"] == s) for s in ("exact", "proxy", "glyph")}
    doc = {
        "note": "Techniques use approved single-frame illustrations generated for Ironvellum, inspired by Everkinetic and "
                "Workout Guide (see docs/ART_ATTRIBUTION.md), or the app's own pictogram. exact: the drawing is the "
                "technique's own movement; proxy: the drawing of the movement it builds on, captioned 'Shown: <movement>' on "
                "the technique sheet; glyph: no honest drawing exists, the pictogram stands in. Generated by "
                "tools/exercise_art/build.py.",
        "counts": count,
        "techniques": rows,
    }
    return (json.dumps(doc, indent=2, ensure_ascii=False) + chr(10)).replace(chr(10), chr(13) + chr(10))


def write(path, text, check):
    data = text.encode("utf-8")
    if check:
        return path.exists() and path.read_bytes() == data
    path.write_bytes(data)
    return True


def slugify(name):
    s = re.sub(r"[^a-z0-9]+", "-", name.lower().replace("→", " to ")).strip("-")
    return s


def approved_art():
    """The slugs the pinned art repo approves: in art/catalogue.json, with a PNG whose sha256 matches the catalogue.
    That is the only approval there is. A missing submodule stops the build; a mismatching PNG is reported and not approved."""
    if not CATALOGUE.exists():
        sys.exit("The art submodule is not initialised: %s is missing.\nRun: git submodule update --init art" % CATALOGUE)
    approved = set()
    for e in json.loads(CATALOGUE.read_text(encoding="utf-8"))["exercises"]:
        png = ART / e["png"]["file"]
        if png.is_file() and hashlib.sha256(png.read_bytes()).hexdigest() == e["png"]["sha256"]:
            approved.add(e["id"])
        else:
            print("not approved (PNG missing or hash differs from art/catalogue.json):", e["id"], file=sys.stderr)
    return approved


def apply_owner(mp):
    """Approved drawings from the art submodule replace the gap they fill: a technique's proxy or pictogram, or a movement's
    placeholder. Returns {art id: hanging}. mp is changed in place."""
    owned = {}
    if not MISSING.exists():
        return owned
    sys.path.insert(0, str(HERE))
    import art
    approved = approved_art()
    counts = json.loads(FRAME_COUNTS.read_text(encoding="utf-8")) if FRAME_COUNTS.exists() else {}
    entries = json.loads(MISSING.read_text(encoding="utf-8"))["entries"]
    if REPLACEMENTS.exists():
        entries += json.loads(REPLACEMENTS.read_text(encoding="utf-8"))["entries"]
    for e in entries:
        files = art.owner_files(ART_PNG, e["slug"])
        # Only slugs the art catalogue approves, and only once every frame the entry asks for is there.
        if e["slug"] not in approved or len(files) < counts.get(e["slug"], e.get("frameCount", 1)):
            continue
        aid = "own_" + e["slug"]
        owned[aid] = bool(e.get("hanging"))
        if e["kind"] == "technique":
            mp["techniques"][e["name"]] = {"exercise": e["name"], "art": aid, "frames": len(files),
                                           "confidence": "owner", "proxy": False}
        else:
            for name in dict.fromkeys([e["name"], *e.get("aliases", [])]):
                mp["mapped"].append({"record": "owner:" + e["slug"], "exercise": name, "confidence": "owner", "art": aid,
                                     "frames": len(files), "source": {"kind": "own", "id": e["slug"]}, "used": True})
            if e.get("technique"):  # the movement's drawing is also the skill-tree technique of the same name
                mp["techniques"][e["name"]] = {"exercise": e["name"], "art": aid, "frames": len(files),
                                               "confidence": "owner", "proxy": False}
            if e.get("sourceArt"):
                for technique in mp["techniques"].values():
                    if technique["art"] == e["sourceArt"]:
                        technique.update(art=aid, frames=len(files))
    return owned


def build_assets(lib, mp, src, workers, owned, owner_only=False, old_report=None):
    """Rebuilds every drawing from the upstream clones and the art submodule; returns the report."""
    import multiprocessing
    sys.path.insert(0, str(HERE))
    import art
    table = art_table(lib, mp)
    ids = {}
    for aid, _ in list(table.values()) + [(t["art"], 0) for t in mp["techniques"].values()]:
        ids[aid] = []
    for name, (aid, _) in table.items():
        ids[aid].append(name)
    jobs = [(aid.split("_", 1)[0], str(ART_PNG) if aid.startswith("own_") else src, aid.split("_", 1)[1],
             owned.get(aid, False) or any(art.HANGING.search(n) for n in names), aid)
            for aid, names in sorted(ids.items()) if aid.startswith("own_") or not owner_only]
    ASSETS.mkdir(parents=True, exist_ok=True)
    report = dict(old_report or {}) if owner_only else {}
    with multiprocessing.Pool(workers) as pool:
        for aid, text, rep in pool.imap_unordered(_job, jobs):
            (ASSETS / (aid + ".paths")).write_bytes(text.encode("utf-8"))
            report[aid] = rep
    for old in list(ASSETS.glob("*")):
        if old.suffix != ".paths" or old.stem not in ids:
            old.unlink()
    report = {k: v for k, v in report.items() if k in ids}
    return dict(sorted(report.items()))


def reweight_assets(workers):
    """Redraws every shipped drawing at the house line weight, in place; for a WEIGHT change without the upstream clones."""
    import multiprocessing
    paths = sorted(ASSETS.glob("*.paths"))
    with multiprocessing.Pool(workers) as pool:
        for path, text in zip(paths, pool.imap(_reweight, paths)):
            path.write_bytes(text.encode("utf-8"))
    print("reweighted", len(paths))


def _reweight(path):
    import art
    return art.reweight_paths(path.read_text(encoding="utf-8"))


def _job(job):
    import art
    kind, src, ident, hanging, aid = job
    text, keep, rep = art.build_one(kind, src, ident, hanging)
    return aid, text, rep


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--workers", type=int, default=6)
    ap.add_argument("--owner-only", action="store_true", help="rebuild only the drawings traced from the art submodule (no --src needed)")
    ap.add_argument("--reweight", action="store_true", help="redraw the shipped drawings at art.WEIGHT (no --src needed)")
    ap.add_argument("--select-stills", action="store_true", help="apply selected still poses to existing vector assets")
    a = ap.parse_args()
    if a.reweight:
        sys.path.insert(0, str(HERE))
        reweight_assets(a.workers)
        return
    lib, mp, guides = load()
    owned = apply_owner(mp)
    if (a.src or a.owner_only) and not a.check:
        old = json.loads(REPORT.read_text(encoding="utf-8")) if REPORT.exists() else {}
        report = build_assets(lib, mp, a.src, a.workers, owned, a.owner_only, old)
        REPORT.write_bytes((json.dumps(report, indent=1, ensure_ascii=False) + chr(10)).replace(chr(10), chr(13) + chr(10)).encode("utf-8"))
        print("drawings", len(report), "animated", sum(1 for r in report.values() if len(r["kept"]) > 1),
              "still", sum(1 for r in report.values() if len(r["kept"]) == 1))
    report = json.loads(REPORT.read_text(encoding="utf-8")) if REPORT.exists() else {}
    selection_path = HERE / "still-selections.json"
    if selection_path.exists():
        sys.path.insert(0, str(HERE))
        from stills import apply_selections
        selections = json.loads(selection_path.read_text(encoding="utf-8"))["selections"]
        # Replaced upstream assets leave the active report; their animations remain archived.
        selections = {aid: choice for aid, choice in selections.items() if aid in report}
        if a.check or a.select_stills or a.src or a.owner_only:
            apply_selections(ASSETS, report, selections, HERE / "animation-sources", check=a.check)
            if not a.check:
                REPORT.write_bytes((json.dumps(report, indent=1, ensure_ascii=False) + chr(10)).replace(chr(10), chr(13) + chr(10)).encode("utf-8"))
    stale = []
    for path, text in ((DOCS / "skill-technique-art.json", technique_doc(mp, report)), (KT / "ExerciseLibrary.kt", library_kt(lib)), (KT / "ExerciseArtIndex.kt", index_kt(lib, mp, report)),
                       (KT / "LibraryGuides.kt", guides_kt(lib, guides))):
        if not write(path, text, a.check):
            stale.append(path.name)
    if a.check:
        ids = {x for v in art_table(lib, mp, report).values() for x in v[:1]} | {t["art"] for t in mp["techniques"].values()}
        missing = sorted(i for i in ids if not (ASSETS / (i + ".paths")).exists())
        if stale or missing:
            print("stale:", stale, "missing assets:", missing)
            sys.exit(1)
        print("exercise art is current")


if __name__ == "__main__":
    main()
