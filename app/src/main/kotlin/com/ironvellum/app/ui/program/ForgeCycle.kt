/**
 * The proposed cycle page: its days, the coverage hint and Apply. Failed (no proposal, an error) shows the
 * greyed previous proposal, the reason and Try again, with Apply disabled; saving freezes the rows and shows
 * "Applying…". Stateless apart from the scroll position.
 */
@Composable
internal fun ForgePlanPage(
    plan: com.ironvellum.app.domain.RoutinePlan?,
    previousPlan: com.ironvellum.app.domain.RoutinePlan?,
    error: String?,
    saving: Boolean,
    catalogueLoaded: Boolean,
    equipment: Equipment?,
    subtitle: String,
    savedRites: Int,
    coveragePresets: List<com.ironvellum.app.domain.PlannedPreset>,
    switchesProgression: Boolean,
    progressionLine: String,
    scroll: androidx.compose.foundation.ScrollState,
    onBack: () -> Unit,
    onCoverage: () -> Unit,
    onOpenEntry: (presetIndex: Int, entryIndex: Int) -> Unit,
    onTryAgain: () -> Unit,
    onApply: () -> Unit,
    onReplace: () -> Unit,
    /** The fatigue estimate, or null before it is read; only ever shown as a hint, never applied to [plan]. */
    fatigue: com.ironvellum.app.domain.FatigueReport? = null,
    onOpenFatigue: () -> Unit = {},
) {
    val hasPlan = plan?.presets?.isNotEmpty() == true
    // A refusal that left no proposal: the generator failed, as distinct from a save that did.
    val failed = plan == null && error != null
    Column(Modifier.fillMaxSize()) {
        Column(Modifier.padding(horizontal = 16.dp)) {
            Spacer(Modifier.height(20.dp))
            ForgeHeader(
                UiText.themed(R.string.forge_proposed_title, R.string.forge_proposed_title__t).asString(),
                onBack,
                subtitle = subtitle.takeIf { hasPlan },
                status = when {
                    failed -> stringResource(R.string.forge_status_failed)
                    saving -> stringResource(R.string.forge_status_saving)
                    else -> null
                },
            )
        }
        Column(
            Modifier
                .weight(1f)
                .verticalScroll(scroll)
                .padding(horizontal = 16.dp),
        ) {
            when {
                hasPlan -> {
                    val current = plan!!
                    ForgeCaption(stringResource(R.string.forge_plan_intro))
                    Spacer(Modifier.height(8.dp))
                    CoverageChip(remember(coveragePresets) { coverageTally(coveragePresets) }, onOpen = onCoverage)
                    // What is still recovering, under the coverage chip: a hint, the plan above is untouched.
                    val rightNow = remember(fatigue) { fatigue?.let { PlanFatigue.rightNow(it, java.time.ZoneId.systemDefault()) } }
                    if (fatigue != null && rightNow != null) {
                        RightNowLine(rightNow, fatigue.nowMs, java.time.ZoneId.systemDefault(), onOpenFatigue)
                    }
                    if (savedRites > 0) {
                        ForgeCaption(UiText.themedPlural(R.plurals.forge_coverage_includes, R.plurals.forge_coverage_includes__t, savedRites).asString())
                    }
                    Spacer(Modifier.height(8.dp))
                    current.presets.forEachIndexed { presetIndex, preset ->
                        if (presetIndex > 0) InkDivider()
                        ProposedDay(
                            preset = preset,
                            editable = !saving,
                            equipment = equipment,
                            onSets = { _, _ -> },
                            onRemove = { },
                            onOpenEntry = if (saving) null else { entryIndex -> onOpenEntry(presetIndex, entryIndex) },
                            showNote = false,
                            folded = true,
                            startOpen = presetIndex == 0,
                            fatigueNotes = fatigue?.let { dayNoteLines(preset, it, java.time.ZoneId.systemDefault()) }.orEmpty(),
                        )
                    }
                    // Routine-wide advice, said once for the whole cycle.
                    Evidence.split(current.note).first.trim().takeIf { it.isNotBlank() }?.let { note ->
                        Spacer(Modifier.height(10.dp))
                        ForgeCaption(note)
                    }
                    // One quiet line, so the progression switch is stated where she acts, not discovered later.
                    if (switchesProgression) ForgeCaption(progressionLine)
                    SourcesPanel(planTexts(current.presets, current.note))
                }
                failed -> {
                    Spacer(Modifier.height(8.dp))
                    previousPlan?.let {
                        ForgePreviousProposal(it)
                        Spacer(Modifier.height(12.dp))
                    }
                    ForgeFailedCard(error!!.removePrefix(UiText.themed(R.string.forge_failed_title, R.string.forge_failed_title__t).asString() + ": ").let { if (it.endsWith(".")) it else "$it." }, onTryAgain)
                }
                else -> ForgeCaption(
                    when {
                        equipment == null -> ARMOURY_REQUIRED
                        !catalogueLoaded -> stringResource(R.string.forge_consulting)
                        else -> stringResource(R.string.forge_nothing_yet)
                    },
                    Modifier.padding(top = 12.dp),
                )
            }
            Spacer(Modifier.height(24.dp))
        }
        ForgeDock(
            primary = stringResource(R.string.common_apply),
            onPrimary = onApply,
            enabled = hasPlan && equipment != null,
            busy = saving,
            note = if (hasPlan && !saving) stringResource(R.string.forge_apply_note) else null,
            link = if (savedRites > 0 && hasPlan) UiText.themed(R.string.forge_replace_link, R.string.forge_replace_link__t).asString() else null,
            linkDanger = true,
            onLink = onReplace,
            above = {
                if (saving) {
                    val count = plan?.presets?.size ?: 0
                    Text(
                        UiText.themedPlural(R.plurals.forge_writing, R.plurals.forge_writing__t, count).asString(),
                        style = MaterialTheme.typography.labelSmall,
                        color = IronvellumColors.InkMuted,
                        modifier = Modifier.padding(bottom = 10.dp),
                    )
                } else if (error != null && !failed) {
                    // A refused write: the cycle on screen is still real, and nothing was written.
                    Text(
                        error,
                        style = MaterialTheme.typography.labelSmall,
                        color = IronvellumColors.DangerRed,
                        modifier = Modifier.padding(bottom = 10.dp),
                    )
                }
            },
        )
    }
}

// ------------------------------------------------------------------ a day

@Composable
private fun ForgeDayPage(
    preset: com.ironvellum.app.domain.PlannedPreset,
    equipment: Equipment?,
    saving: Boolean,
    openEntry: String?,
    onToggle: (String) -> Unit,
    scroll: androidx.compose.foundation.ScrollState,
    onBack: () -> Unit,
    onSets: (entryIndex: Int, delta: Int) -> Unit,
    onLoad: (entryIndex: Int, delta: Int) -> Unit,
    onSwap: (entryIndex: Int) -> Unit,
    onRemove: (entryIndex: Int) -> Unit,
    onAdd: () -> Unit,
    onDone: () -> Unit,
) {
    val day = dayLabel(preset.scheduledDay)
    Column(Modifier.fillMaxSize()) {
        Column(Modifier.padding(horizontal = 16.dp)) {
            Spacer(Modifier.height(20.dp))
            ForgeHeader(day, onBack, subtitle = dayHeadline(preset))
        }
        Column(
            Modifier
                .weight(1f)
                .verticalScroll(scroll)
                .padding(horizontal = 16.dp),
        ) {
            ForgeLabel(stringResource(R.string.forge_movements_heading))
            preset.entries.forEachIndexed { entryIndex, entry ->
                val key = entryKey(entry)
                ProposedEntryRow(
                    entry = entry,
                    dayName = day,
                    equipment = equipment,
                    editable = !saving,
                    expanded = openEntry == key,
                    onToggle = { onToggle(key) },
                    onSets = { delta -> onSets(entryIndex, delta) },
                    onLoad = { delta -> onLoad(entryIndex, delta) },
                    onSwap = { onSwap(entryIndex) },
                    onRemove = { onRemove(entryIndex) },
                )
                InkDivider()
            }
            Row(
                Modifier
                    .fillMaxWidth()
                    .heightIn(min = 52.dp)
                    .clickable(enabled = !saving, role = Role.Button, onClickLabel = UiText.res(R.string.forge_add_movement_to, day).asString(), onClick = onAdd),
                verticalAlignment = Alignment.CenterVertically,
                horizontalArrangement = Arrangement.spacedBy(12.dp),
            ) {
                Text("+", style = MaterialTheme.typography.titleMedium, color = IronvellumColors.SystemGreen)
                Text(stringResource(R.string.forge_add_movement), style = MaterialTheme.typography.bodyMedium, color = IronvellumColors.SystemGreen)
            }
            Spacer(Modifier.height(16.dp))
        }
        ForgeDock(primary = stringResource(R.string.common_done), onPrimary = onDone)
    }
}
