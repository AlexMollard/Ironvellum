/*
 * Forge a cycle, v2: three steps (Goal, Kit, Focus) in one tabbed form, then the proposed cycle, then a day
 * opened for editing. The answers live in the view model, so the form keeps them across Back and rotation;
 * the step and page are saved with the screen. A hint on coverage never blocks Apply.
 */

internal enum class ForgePhase { FORM, PLAN, DAY }

private const val PICK_NONE = 0
private const val PICK_SWAP = 1
private const val PICK_ADD = 2

internal const val ARMOURY_REQUIRED = "Pick your armoury to continue. Nothing means bodyweight only."

private val STEP_LABELS = listOf("Goal", "Kit", "Focus")

@Composable
internal fun ForgeCycleScreen(vm: ProgramBuilderViewModel, onDone: () -> Unit) {
    val catalogue by vm.catalogue.collectAsStateWithLifecycle()
    val presets by vm.presets.collectAsStateWithLifecycle()
    val saving by vm.saving.collectAsStateWithLifecycle()
    val baseline by vm.baseline.collectAsStateWithLifecycle()
    val generated by vm.generatedPlan.collectAsStateWithLifecycle()
    val plan by vm.plan.collectAsStateWithLifecycle()
    val previousPlan by vm.previousPlan.collectAsStateWithLifecycle()
    val error by vm.error.collectAsStateWithLifecycle()
    val equipment by vm.equipment.collectAsStateWithLifecycle()
    val focus by vm.focus.collectAsStateWithLifecycle()
    val tier by vm.tier.collectAsStateWithLifecycle()
    val daysPerWeek by vm.daysPerWeek.collectAsStateWithLifecycle()
    val split by vm.split.collectAsStateWithLifecycle()
    val priorities by vm.priorities.collectAsStateWithLifecycle()
    val compoundOnly by vm.compoundOnly.collectAsStateWithLifecycle()
    val maxExercises by vm.maxExercises.collectAsStateWithLifecycle()
    val sessionMinutes by vm.sessionMinutes.collectAsStateWithLifecycle()

    var step by rememberSaveable { mutableIntStateOf(0) }
    var phase by rememberSaveable { mutableStateOf(ForgePhase.FORM) }
    var dayIndex by rememberSaveable { mutableIntStateOf(0) }
    var openEntry by rememberSaveable { mutableStateOf<String?>(null) }
    var picker by rememberSaveable { mutableIntStateOf(PICK_NONE) }
    var pickEntry by rememberSaveable { mutableIntStateOf(0) }
    var coverageOpen by rememberSaveable { mutableStateOf(false) }
    var armouryOpen by rememberSaveable { mutableStateOf(false) }
    var moreOpen by rememberSaveable { mutableStateOf(false) }
    var confirmDiscard by rememberSaveable { mutableStateOf(false) }
    var confirmReplace by rememberSaveable { mutableStateOf(false) }
    var daySheet by rememberSaveable { mutableStateOf(false) }
    val stepScrolls = List(STEP_LABELS.size) { rememberScrollState() }
    val planScroll = rememberScrollState()
    val dayScroll = rememberScrollState()

    // Something to lose: answers moved off the first proposal's, or its days edited.
    val answers = vm.answersNow()
    val dirty = baseline != null && (answers != baseline || plan != generated)
    val edits = remember(generated, plan) { planEdits(generated, plan) }
    // The cycle the proposal makes: a week joins the saved cycle, so those rites count too.
    val coveragePresets = remember(plan, presets) { proposalCoveragePresets("week", plan?.presets, null, presets, null) }

    val goBack = {
        when {
            phase == ForgePhase.DAY -> {
                openEntry = null
                phase = ForgePhase.PLAN
            }
            phase == ForgePhase.PLAN -> phase = ForgePhase.FORM
            step > 0 -> step -= 1
            dirty -> confirmDiscard = true
            else -> onDone()
        }
    }
    if (coverageOpen) {
        BackHandler { coverageOpen = false }
        CoveragePreviewScreen(coveragePresets) { coverageOpen = false }
        return
    }
    BackHandler(enabled = true) { goBack() }

    // A day that no longer exists (its last movement was removed) has nothing to show: back to the proposal.
    val dayPreset = plan?.presets?.getOrNull(dayIndex)
    LaunchedEffect(phase, dayPreset == null) {
        if (phase == ForgePhase.DAY && dayPreset == null) phase = ForgePhase.PLAN
    }

    val apply = {
        val current = plan
        if (current != null && !saving) {
            if (presets.isEmpty() || !dayConflict(current, presets).hasClash) vm.addPresets(onDone) else daySheet = true
        }
    }

    when (phase) {
        ForgePhase.FORM -> ForgeFormPage(
            step = step,
            onStep = { step = it },
            scroll = stepScrolls[step],
            onBack = goBack,
            focus = focus,
            onFocus = vm::setFocus,
            split = split,
            days = daysPerWeek,
            onSplit = { s -> vm.setSplit(s, daysAfterSplit(s, daysPerWeek)) },
            onDays = { d -> vm.setSplit(splitAfterDays(split, d), d) },
            equipment = equipment,
            onArmoury = { armouryOpen = true },
            sessionMinutes = sessionMinutes,
            onSessionMinutes = { vm.sessionMinutes.value = it },
            tier = tier,
            compoundOnly = compoundOnly,
            maxExercises = maxExercises,
            onMore = { moreOpen = true },
            priorities = priorities,
            onPriority = vm::togglePriority,
            onNext = { if (step < STEP_LABELS.lastIndex) step += 1 else phase = ForgePhase.PLAN },
        )
        ForgePhase.PLAN -> ForgePlanPage(
            plan = plan,
            previousPlan = previousPlan,
            error = error,
            saving = saving,
            catalogueLoaded = catalogue.isNotEmpty(),
            equipment = equipment,
            subtitle = cycleSubtitle(daysPerWeek, split),
            savedRites = presets.size,
            coveragePresets = coveragePresets,
            switchesProgression = vm.switchesProgression(),
            progressionLine = vm.progressionLine(),
            scroll = planScroll,
            onBack = goBack,
            onCoverage = { coverageOpen = true },
            onOpenEntry = { presetIndex, entryIndex ->
                plan?.presets?.getOrNull(presetIndex)?.entries?.getOrNull(entryIndex)?.let { entry ->
                    dayIndex = presetIndex
                    openEntry = entryKey(entry)
                    phase = ForgePhase.DAY
                }
            },
            onTryAgain = vm::retry,
            onApply = apply,
            onReplace = { confirmReplace = true },
        )
        ForgePhase.DAY -> if (dayPreset != null) {
            ForgeDayPage(
                preset = dayPreset,
                equipment = equipment,
                saving = saving,
                openEntry = openEntry,
                onToggle = { key -> openEntry = if (openEntry == key) null else key },
                scroll = dayScroll,
                onBack = goBack,
                onSets = { entryIndex, delta -> vm.editEntry(dayIndex, entryIndex) { it.withSetsDelta(delta) } },
                onLoad = { entryIndex, delta ->
                    vm.editEntry(dayIndex, entryIndex) { entry ->
                        val cap = equipment?.let { ProgramGenerator.dumbbellCapKg(entry.exerciseName, it) }
                        entry.withLoadDelta(delta, loadStepKg(Units.current), cap, wornFor(entry, equipment), Units.current)
                    }
                },
                onSwap = { entryIndex ->
                    pickEntry = entryIndex
                    picker = PICK_SWAP
                },
                onRemove = { entryIndex ->
                    openEntry = null
                    vm.removeEntry(dayIndex, entryIndex)
                },
                onAdd = { picker = PICK_ADD },
                onDone = {
                    openEntry = null
                    phase = ForgePhase.PLAN
                },
            )
        }
    }

    if (picker != PICK_NONE) {
        ExercisePickerSheet(
            exercises = catalogue,
            title = if (picker == PICK_SWAP) "Swap movement" else "Add movement",
            onPick = { exercise ->
                if (picker == PICK_SWAP) vm.swapEntry(dayIndex, pickEntry, exercise) else vm.addEntry(dayIndex, exercise)
                openEntry = null
                picker = PICK_NONE
            },
            onDismiss = { picker = PICK_NONE },
        )
    }

    if (armouryOpen) {
        IronvellumDialog(
            onDismissRequest = { armouryOpen = false },
            title = { Text("Armoury") },
            text = { GearPicker(equipment = equipment, onChange = { vm.equipment.value = it }) },
            confirmButton = { IronvellumButton(label = "Done", onClick = { armouryOpen = false }) },
        )
    }

    if (moreOpen) {
        IronvellumDialog(
            onDismissRequest = { moreOpen = false },
            title = { Text("More options") },
            text = {
                MoreOptionsBody(
                    tier = tier,
                    onTier = vm::setTier,
                    compoundOnly = compoundOnly,
                    onCompound = { vm.compoundOnly.value = it },
                    maxExercises = maxExercises,
                    onMaxExercises = { vm.maxExercises.value = it },
                    showTier = true,
                    sessionMinutes = null,
                    onSessionMinutes = {},
                )
            },
            confirmButton = { IronvellumButton(label = "Done", onClick = { moreOpen = false }) },
        )
    }

    if (confirmDiscard) {
        ForgeDiscardSheet(
            edits = edits,
            answersChanged = baseline != null && answers != baseline,
            onKeep = { confirmDiscard = false },
            onDiscard = {
                confirmDiscard = false
                onDone()
            },
        )
    }

    if (daySheet) {
        val current = plan
        if (current != null) {
            val conflict = remember(current, presets) { dayConflict(current, presets) }
            ForgeAddConflictSheet(
                conflict = conflict,
                savedRites = presets.size,
                takenDays = presets.mapNotNull { it.scheduledDay }.distinct(),
                onFit = {
                    daySheet = false
                    vm.addPresets(onDone)
                },
                onReplace = {
                    daySheet = false
                    vm.replacePresets(onDone)
                },
                onCancel = { daySheet = false },
            )
        } else {
            daySheet = false
        }
    }

    if (confirmReplace) {
        IronvellumDialog(
            onDismissRequest = { confirmReplace = false },
            title = { Text("Replace your cycle?") },
            text = {
                Text(
                    "Your ${presets.size} current ${if (presets.size == 1) "rite" else "rites"} will be deleted " +
                        "and the forged cycle takes their place. Your Chronicle is untouched." +
                        if (vm.switchesProgression()) " " + vm.progressionLine() else "",
                )
            },
            confirmButton = {
                IronvellumButton(
                    label = "Replace",
                    onClick = {
                        confirmReplace = false
                        vm.replacePresets(onDone)
                    },
                    danger = true,
                )
            },
            dismissButton = {
                IronvellumButton(label = "Keep mine", onClick = { confirmReplace = false }, quiet = true)
            },
        )
    }
}

// ------------------------------------------------------------------ the form

@Composable
private fun ForgeFormPage(
    step: Int,
    onStep: (Int) -> Unit,
    scroll: androidx.compose.foundation.ScrollState,
    onBack: () -> Unit,
    focus: TrainingFocus,
    onFocus: (TrainingFocus) -> Unit,
    split: TrainingSplit,
    days: Int,
    onSplit: (TrainingSplit) -> Unit,
    onDays: (Int) -> Unit,
    equipment: Equipment?,
    onArmoury: () -> Unit,
    sessionMinutes: Int,
    onSessionMinutes: (Int) -> Unit,
    tier: VolumeLevel,
    compoundOnly: Boolean,
    maxExercises: Int,
    onMore: () -> Unit,
    priorities: Set<MuscleArea>,
    onPriority: (MuscleArea) -> Unit,
    onNext: () -> Unit,
) {
    Column(Modifier.fillMaxSize()) {
        Column(Modifier.padding(horizontal = 16.dp)) {
            Spacer(Modifier.height(20.dp))
            ForgeHeader("Forge a cycle", onBack)
            ForgeStepTabs(step, STEP_LABELS, onStep)
        }
        Column(
            Modifier
                .weight(1f)
                .verticalScroll(scroll)
                .padding(horizontal = 16.dp),
        ) {
            when (step) {
                0 -> ForgeGoalStep(focus, onFocus, split, days, onSplit, onDays)
                1 -> ForgeKitStep(equipment, onArmoury, sessionMinutes, onSessionMinutes, tier, compoundOnly, maxExercises, onMore)
                else -> ForgeFocusStep(priorities, onPriority)
            }
            Spacer(Modifier.height(16.dp))
        }
        val ready = step == 0 || equipment != null
        ForgeDock(
            primary = when (step) {
                0 -> "Next: kit"
                1 -> "Next: focus"
                else -> "Forge cycle"
            },
            onPrimary = onNext,
            enabled = ready,
            note = when {
                !ready -> ARMOURY_REQUIRED
                step == 0 -> "Step 1 of 3"
                step == 1 -> "Step 2 of 3"
                else -> "You can change every number on the next screen."
            },
        )
    }
}

private fun goalCaption(focus: TrainingFocus): String = when (focus) {
    TrainingFocus.STRENGTH -> "Heavier loads on the main lifts. Hard sets are the dose; reps just guide the weight."
    TrainingFocus.MUSCLE -> "Higher volume, moderate load. Hard sets are the dose; reps just guide the weight."
    TrainingFocus.SKILL -> "Handstands, levers, the planche. Practice over pump."
    TrainingFocus.GENERAL -> "A balanced mix: a bit stronger, a bit bigger, nothing neglected."
}

@Composable
private fun ForgeGoalStep(
    focus: TrainingFocus,
    onFocus: (TrainingFocus) -> Unit,
    split: TrainingSplit,
    days: Int,
    onSplit: (TrainingSplit) -> Unit,
    onDays: (Int) -> Unit,
) {
    ForgeLabel("Aim")
    ForgeRadioRow(
        label = "Goal",
        options = listOf(
            TrainingFocus.STRENGTH to "Power",
            TrainingFocus.MUSCLE to "Muscle",
            TrainingFocus.SKILL to "Techniques",
            TrainingFocus.GENERAL to "Mixed",
        ),
        selected = focus,
        onPick = onFocus,
    )
    ForgeCaption(goalCaption(focus))
    ForgeLabel("Week")
    ForgeRadioRow(
        label = "Week split",
        options = FORGE_SPLITS.map { it to it.label },
        selected = split,
        onPick = onSplit,
    )
    ForgeCaption(splitCaption(split, days))
    ForgeLabel("Days per week")
    ForgeRadioRow(
        label = "Days per week",
        options = FORGE_DAYS.map { it to it.toString() },
        selected = days,
        onPick = onDays,
    )
}

@Composable
private fun ForgeKitStep(
    equipment: Equipment?,
    onArmoury: () -> Unit,
    sessionMinutes: Int,
    onSessionMinutes: (Int) -> Unit,
    tier: VolumeLevel,
    compoundOnly: Boolean,
    maxExercises: Int,
    onMore: () -> Unit,
) {
    ForgeLabel("Kit")
    InkDivider()
    ListRow(
        label = "Armoury",
        value = SettingsSummaries.armoury(equipment),
        onClickLabel = "Choose your armoury",
        onClick = onArmoury,
    )
    InkDivider()
    ForgeLabel("Rite length")
    ForgeRadioRow(
        label = "Rite length",
        options = ProgramRules.SESSION_MINUTES_OPTIONS.map { it to "$it min" },
        selected = sessionMinutes,
        onPick = onSessionMinutes,
    )
    ForgeCaption("The Forge fits each rite inside this time, warm-up left out.")
    Spacer(Modifier.height(10.dp))
    InkDivider()
    ListRow(
        label = "More options",
        value = (if (compoundOnly) "Compound · " else "") + "${tier.label} sets · $maxExercises per rite",
        onClickLabel = "More options: starting sets, compound only, exercises per rite",
        onClick = onMore,
    )
    InkDivider()
}

@Composable
private fun ForgeFocusStep(priorities: Set<MuscleArea>, onPriority: (MuscleArea) -> Unit) {
    ForgeLabel("Priorities · up to 3 · ${priorities.size} picked")
    FlowRow(
        horizontalArrangement = Arrangement.spacedBy(8.dp),
        verticalArrangement = Arrangement.spacedBy(8.dp),
        modifier = Modifier.fillMaxWidth(),
    ) {
        MuscleArea.entries.forEach { area ->
            // Checkbox role: the check alone is invisible to a screen reader.
            PickCell(
                label = area.label,
                selected = area in priorities,
                role = Role.Checkbox,
                onClick = { onPriority(area) },
            )
        }
    }
    ForgeCaption("Priorities get an extra hard set or two each week. Skip this and every muscle is treated the same.")
}

/**
 * The options most lifters leave alone. [showTier] is the Forge's starting-sets answer (the classic pages keep
 * it on the page); [sessionMinutes] non-null adds the rite length there.
 */
@Composable
internal fun MoreOptionsBody(
    tier: VolumeLevel,
    onTier: (VolumeLevel) -> Unit,
    compoundOnly: Boolean,
    onCompound: (Boolean) -> Unit,
    maxExercises: Int,
    onMaxExercises: (Int) -> Unit,
    showTier: Boolean,
    sessionMinutes: Int?,
    onSessionMinutes: (Int) -> Unit,
) {
    Column {
        if (showTier) {
            Text("Starting sets", style = MaterialTheme.typography.labelMedium, color = IronvellumColors.InkMuted)
            Spacer(Modifier.height(6.dp))
            ForgeRadioRow(
                label = "Starting sets",
                options = VolumeLevel.entries.map { it to it.label },
                selected = tier,
                onPick = onTier,
            )
            ForgeCaption(startingSetsCaption(tier))
            Spacer(Modifier.height(12.dp))
        }
        if (sessionMinutes != null) {
            Text("Rite length", style = MaterialTheme.typography.labelMedium, color = IronvellumColors.InkMuted)
            Spacer(Modifier.height(6.dp))
            ForgeRadioRow(
                label = "Rite length",
                options = ProgramRules.SESSION_MINUTES_OPTIONS.map { it to "$it min" },
                selected = sessionMinutes,
                onPick = onSessionMinutes,
            )
            Spacer(Modifier.height(12.dp))
        }
        // The same drawn toggle cell as the gear items.
        PickCell(
            label = "Compound & technique only",
            selected = compoundOnly,
            modifier = Modifier.fillMaxWidth(),
            description = "Compound & technique only, ${if (compoundOnly) "on" else "off"}",
            role = Role.Checkbox,
            onClick = { onCompound(!compoundOnly) },
        )
        ForgeCaption("No curls, raises, calf, bridge or machine isolation work.")
        Spacer(Modifier.height(12.dp))
        Row(
            horizontalArrangement = Arrangement.spacedBy(6.dp),
            verticalAlignment = Alignment.CenterVertically,
            modifier = Modifier.fillMaxWidth(),
        ) {
            Text(
                "Max exercises per rite",
                style = MaterialTheme.typography.bodyMedium,
                color = IronvellumColors.Ink,
                modifier = Modifier.weight(1f),
            )
            TapPad(
                label = "−",
                description = "Fewer exercises per rite, currently $maxExercises",
                onClick = { onMaxExercises((maxExercises - 1).coerceAtLeast(ProgramRules.MAX_EXERCISES_RANGE.first)) },
            )
            Text(
                maxExercises.toString(),
                style = MaterialTheme.typography.labelLarge,
                fontFamily = ChakraPetch,
                color = IronvellumColors.Ink,
            )
            TapPad(
                label = "+",
                description = "More exercises per rite, currently $maxExercises",
                onClick = { onMaxExercises((maxExercises + 1).coerceAtMost(ProgramRules.MAX_EXERCISES_RANGE.last)) },
            )
        }
    }
}

